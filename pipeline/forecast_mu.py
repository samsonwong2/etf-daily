"""Production forecast-mu override preparation.

The default production mean source is a causal EWMA60 panel shrunk toward zero
with alpha=0.75.  The same Route-A-style override contract can also carry
trend-aware rolling mean models generated by ``build_rolling_mean_route_a_override``.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import pandas as pd

from .constants import (
    PRODUCTION_FORECAST_MU_ASOF_LAG,
    PRODUCTION_FORECAST_MU_EWMA_SPAN,
    PRODUCTION_FORECAST_MU_METHOD,
    PRODUCTION_FORECAST_MU_MIN_PERIODS,
    PRODUCTION_FORECAST_MU_MISSING_FILL,
    PRODUCTION_FORECAST_MU_SHRINK_ALPHA,
    PRODUCTION_FORECAST_MU_SHRINK_TARGET,
    REPO_ROOT,
)
from .infra import _run_command


FORECAST_MU_METHOD_CHOICES = (PRODUCTION_FORECAST_MU_METHOD, "route_a")
FORECAST_MU_MODEL_CHOICES = (
    "rolling_mean",
    "ewma",
    "multi_window_mean",
    "momentum",
    "vol_adjusted_momentum",
    "ic_weighted_ensemble",
    "regime_ic_weighted_ensemble",
    "regime_switch_ewma_multi_window",
    "regime_switch_ewma_shrink",
)


def _compact_date(value: str) -> str:
    return value.replace("-", "")


def _alpha_tag(value: float) -> str:
    return f"{value:g}".replace(".", "p")


def _model_tag(args: argparse.Namespace) -> str:
    model = str(getattr(args, "forecast_mu_model", "ewma"))
    if model == "ewma":
        span = int(getattr(args, "forecast_mu_ewma_span", PRODUCTION_FORECAST_MU_EWMA_SPAN))
        return f"ewma{span}"
    aliases = {
        "regime_switch_ewma_shrink": "rs_ewma_shrink",
        "regime_switch_ewma_multi_window": "rs_ewma_multi",
        "regime_ic_weighted_ensemble": "rs_ic_ens",
        "ic_weighted_ensemble": "ic_ens",
        "vol_adjusted_momentum": "vol_mom",
        "multi_window_mean": "multi_mean",
        "rolling_mean": "roll_mean",
    }
    if model in aliases:
        return aliases[model]
    return model


def _default_output_dir(args: argparse.Namespace, start_date: str, end_date: str) -> Path:
    temp_dir = Path(args.temp_dir).expanduser().resolve()
    alpha = _alpha_tag(float(getattr(args, "forecast_mu_shrink_alpha", PRODUCTION_FORECAST_MU_SHRINK_ALPHA)))
    return temp_dir / (
        f"fmu_{_model_tag(args)}_"
        f"s{alpha}_{_compact_date(start_date)}_{_compact_date(end_date)}"
    )


def normalize_forecast_mu_args(args: argparse.Namespace) -> None:
    """Normalize production forecast-mu args before path resolution."""
    if getattr(args, "mean_override_csv", None):
        return
    if getattr(args, "forecast_mu_method", "route_a") == "route_a":
        return
    if args.forecast_mu_method != PRODUCTION_FORECAST_MU_METHOD:
        raise ValueError(
            f"Unsupported forecast_mu_method={args.forecast_mu_method!r}; "
            f"production is locked to {PRODUCTION_FORECAST_MU_METHOD!r}."
        )

    forecast_start = args.forecast_mu_start_date or args.route_a_start_date or args.start_date
    output_dir = (
        Path(args.forecast_mu_output_dir).expanduser().resolve()
        if args.forecast_mu_output_dir
        else Path(args.route_a_output_dir).expanduser().resolve()
        if args.route_a_output_dir
        else _default_output_dir(args, forecast_start, args.end_date)
    )

    args.forecast_mu_start_date = forecast_start
    args.forecast_mu_output_dir = str(output_dir)
    args.route_a_start_date = forecast_start
    args.route_a_output_dir = str(output_dir)
    if args.mode != "reuse-route-a":
        print(
            f"[INFO] forecast_mu_method={args.forecast_mu_method} supplied; "
            f"switching --mode {args.mode} -> reuse-route-a so the bridge consumes "
            "the generated production forecast-mu files."
        )
        args.mode = "reuse-route-a"


def _validate_status(status: pd.DataFrame, *, allow_incomplete: bool) -> None:
    if "status" not in status.columns:
        raise ValueError("forecast-mu status file is missing the status column")
    bad = status.loc[status["status"].astype(str) != "ok"].copy()
    if bad.empty:
        return
    if allow_incomplete:
        print(f"[WARN] Production forecast-mu has {len(bad)} incomplete instruments; continuing by request.")
        return
    preview = bad[["instrument", "status", "message"]].head(20).to_string(index=False)
    raise ValueError(
        "Production forecast-mu coverage is incomplete. Pass --forecast-mu-allow-incomplete "
        f"to continue anyway. First bad rows:\n{preview}"
    )


def _read_cluster_mapping_instruments(path: Path) -> list[str]:
    instruments: list[str] = []
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        instruments.append(line.split()[0].upper())
    return instruments


def _instrument_universe_sha1(instruments: list[str]) -> str:
    payload = "\n".join(sorted(set(instruments))).encode("utf-8")
    return hashlib.sha1(payload).hexdigest()


def _validate_status_universe(
    status: pd.DataFrame,
    *,
    cluster_mapping_path: Path,
    output_dir: Path,
) -> list[str]:
    if "instrument" not in status.columns:
        raise ValueError(f"forecast-mu status file is missing the instrument column: {output_dir}")
    requested = set(_read_cluster_mapping_instruments(cluster_mapping_path))
    existing = set(status["instrument"].astype(str).str.upper())
    missing = sorted(requested - existing)
    extra = sorted(existing - requested)
    if missing or extra:
        missing_preview = ", ".join(missing[:20]) + (" ..." if len(missing) > 20 else "")
        extra_preview = ", ".join(extra[:20]) + (" ..." if len(extra) > 20 else "")
        raise ValueError(
            "Production forecast-mu directory was built for a different instrument universe. "
            f"output_dir={output_dir}; cluster_mapping={cluster_mapping_path}; "
            f"missing_current={len(missing)} [{missing_preview}]; "
            f"extra_existing={len(extra)} [{extra_preview}]. "
            "Use a fresh --forecast-mu-output-dir or pass --forecast-mu-overwrite after changing the pool."
        )
    return sorted(requested)


