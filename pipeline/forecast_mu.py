def _same_config_value(left: object, right: object) -> bool:
    if left is None or right is None:
        return left is right
    if isinstance(left, float) or isinstance(right, float):
        try:
            return abs(float(left) - float(right)) <= 1e-12
        except (TypeError, ValueError):
            return False
    return left == right


def _validate_reuse_config(args: argparse.Namespace, output_dir: Path) -> None:
    manifest_path = output_dir / "production_forecast_mu_manifest.json"
    if not manifest_path.exists():
        print(
            f"[WARN] Reusing forecast-mu dir without production manifest; "
            f"cannot verify model config: {output_dir}"
        )
        return
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    expected = _expected_forecast_mu_config(args)
    mismatches: list[str] = []
    for key, expected_value in expected.items():
        actual_value = manifest.get(key)
        if not _same_config_value(actual_value, expected_value):
            mismatches.append(f"{key}: existing={actual_value!r}, requested={expected_value!r}")
    if mismatches:
        preview = "; ".join(mismatches[:12])
        raise ValueError(
            "Production forecast-mu directory was built with a different model config. "
            f"output_dir={output_dir}; {preview}. "
            "Use a fresh --forecast-mu-output-dir or pass --forecast-mu-overwrite."
        )


def _write_production_manifest(args: argparse.Namespace, output_dir: Path, status: pd.DataFrame) -> None:
    cluster_mapping_path = Path(args.cluster_mapping_path).expanduser().resolve()
    instruments = _read_cluster_mapping_instruments(cluster_mapping_path)
    manifest = {
        "mode": "production_forecast_mu_override",
        "forecast_mu_method": PRODUCTION_FORECAST_MU_METHOD,
        **_expected_forecast_mu_config(args),
        "forecast_start_date": args.forecast_mu_start_date,
        "forecast_end_date": args.end_date,
        "history_start_date": args.forecast_mu_history_start_date,
        "initial_annualized_csv": args.forecast_mu_initial_annualized_csv,
        "output_dir": str(output_dir),
        "cluster_mapping_path": str(cluster_mapping_path),
        "instrument_universe_sha1": _instrument_universe_sha1(instruments),
        "tickers_requested": int(len(status)),
        "tickers_ok": int((status["status"].astype(str) == "ok").sum()),
        "mu_preset": args.mu_preset,
        "mean_overlay_mode": args.mean_overlay_mode,
    }
    (output_dir / "production_forecast_mu_manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True),
        encoding="utf-8",
    )


def prepare_forecast_mu_route_a(args: argparse.Namespace, paths: dict[str, Path]) -> None:
    """Create or validate the production forecast-mu Route-A override directory."""
    if getattr(args, "mean_override_csv", None):
        return
    if getattr(args, "forecast_mu_method", "route_a") == "route_a":
        return

    output_dir = paths["route_a_output_dir"]
    status_path = output_dir / "rolling_mean_override_status.csv"
    if output_dir.exists() and not args.forecast_mu_overwrite:
        if not status_path.exists():
            raise FileExistsError(
                f"forecast-mu output dir exists without status CSV: {output_dir}. "
                "Pass --forecast-mu-overwrite to rebuild it, or use --forecast-mu-method route_a."
            )
        status = pd.read_csv(status_path)
        cluster_mapping_path = Path(args.cluster_mapping_path).expanduser().resolve()
        requested_instruments = _validate_status_universe(
            status,
            cluster_mapping_path=cluster_mapping_path,
            output_dir=output_dir,
        )
        _validate_reuse_config(args, output_dir)
        _validate_status(status, allow_incomplete=args.forecast_mu_allow_incomplete)
        _write_production_manifest(args, output_dir, status)
        print(
            f"[INFO] Reusing production forecast-mu dir: {output_dir} "
            f"method={PRODUCTION_FORECAST_MU_METHOD} model={getattr(args, 'forecast_mu_model', 'ewma')} "
            f"shrink_alpha={float(getattr(args, 'forecast_mu_shrink_alpha', PRODUCTION_FORECAST_MU_SHRINK_ALPHA)):g} "
            f"ok={(status['status'].astype(str) == 'ok').sum()}/{len(status)} "
            f"universe_sha1={_instrument_universe_sha1(requested_instruments)[:12]}"
        )
        return

    command = [
        sys.executable,
        str(REPO_ROOT / "fund_pool_builder" / "build_rolling_mean_route_a_override.py"),
        "--forecast-start-date",
        args.forecast_mu_start_date,
        "--forecast-end-date",
        args.end_date,
        "--cluster-mapping",
        str(Path(args.cluster_mapping_path).expanduser().resolve()),
        "--provider-uri",
        str(args.provider_uri),
        "--output-dir",
        str(output_dir),
        "--mean-model",
        str(getattr(args, "forecast_mu_model", "ewma")),
        "--window",
        str(int(getattr(args, "forecast_mu_window", 252))),
        "--ewma-span",
        str(int(getattr(args, "forecast_mu_ewma_span", PRODUCTION_FORECAST_MU_EWMA_SPAN))),
        "--multi-windows",
        str(getattr(args, "forecast_mu_multi_windows", "20,60,120,252")),
        "--momentum-window",
        str(int(getattr(args, "forecast_mu_momentum_window", 60))),
        "--vol-window",
        str(int(getattr(args, "forecast_mu_vol_window", 60))),
        "--ensemble-ewma-spans",
        str(getattr(args, "forecast_mu_ensemble_ewma_spans", "20,60,120,252")),
        "--ensemble-momentum-windows",
        str(getattr(args, "forecast_mu_ensemble_momentum_windows", "20,60,120")),
        "--ensemble-vol-adjusted-windows",
        str(getattr(args, "forecast_mu_ensemble_vol_adjusted_windows", "60,120")),
        "--ic-lookback",
        str(int(getattr(args, "forecast_mu_ic_lookback", 60))),
        "--ic-min-periods",
        str(int(getattr(args, "forecast_mu_ic_min_periods", 20))),
        "--regime-benchmark",
        str(getattr(args, "forecast_mu_regime_benchmark", "SH510300")),
        "--regime-fast-ma",
        str(int(getattr(args, "forecast_mu_regime_fast_ma", 20))),
        "--regime-slow-ma",
        str(int(getattr(args, "forecast_mu_regime_slow_ma", 60))),
        "--regime-vol-window",
        str(int(getattr(args, "forecast_mu_regime_vol_window", 20))),
        "--regime-vol-lookback",
        str(int(getattr(args, "forecast_mu_regime_vol_lookback", 120))),
        "--regime-risk-off-shrink-alpha",
        str(float(getattr(args, "forecast_mu_regime_risk_off_shrink_alpha", 0.50))),
        "--mu-scale",
        str(float(getattr(args, "forecast_mu_scale", 1.0))),
        "--shrink-target",
        str(getattr(args, "forecast_mu_shrink_target", PRODUCTION_FORECAST_MU_SHRINK_TARGET)),
        "--shrink-alpha",
        str(float(getattr(args, "forecast_mu_shrink_alpha", PRODUCTION_FORECAST_MU_SHRINK_ALPHA))),
        "--min-periods",
        str(int(getattr(args, "forecast_mu_min_periods", PRODUCTION_FORECAST_MU_MIN_PERIODS))),
        "--asof-lag",
        str(int(getattr(args, "forecast_mu_asof_lag", PRODUCTION_FORECAST_MU_ASOF_LAG))),
        "--missing-mu-fill",
        str(getattr(args, "forecast_mu_missing_fill", PRODUCTION_FORECAST_MU_MISSING_FILL)),
        "--overwrite",
    ]
    if str(getattr(args, "forecast_mu_multi_window_weights", "")).strip():
        command.extend(["--multi-window-weights", str(args.forecast_mu_multi_window_weights)])
    if getattr(args, "forecast_mu_winsor_quantile", None) is not None:
        command.extend(["--winsor-quantile", str(args.forecast_mu_winsor_quantile)])
    if args.forecast_mu_history_start_date:
        command.extend(["--history-start-date", str(args.forecast_mu_history_start_date)])
    if args.forecast_mu_initial_annualized_csv:
        command.extend(["--initial-annualized-csv", str(args.forecast_mu_initial_annualized_csv)])
    if args.forecast_mu_no_initial_fallback:
        command.append("--no-initial-fallback")
    raw_panel_path = paths.get("raw_panel_out")
    if raw_panel_path is not None and Path(raw_panel_path).exists():
        command.extend(["--raw-panel-path", str(Path(raw_panel_path).expanduser().resolve())])

    _run_command(command, REPO_ROOT, "production forecast-mu override")
    if not status_path.exists():
        if getattr(args, "dry_run", False):
            return
        raise FileNotFoundError(f"forecast-mu builder did not write status CSV: {status_path}")
    status = pd.read_csv(status_path)
    _validate_status(status, allow_incomplete=args.forecast_mu_allow_incomplete)
    _write_production_manifest(args, output_dir, status)
